    page: {
        flexDirection: 'column',
        backgroundColor: '#FCFDFC',
        padding: 30,
        fontFamily: 'Helvetica'
    },
    watermarkContainer: {
        position: 'absolute',
        top: '35%',
        left: '10%',
        opacity: 0.06,
        transform: 'rotate(-45deg)'
    },
    watermarkText: {
        fontSize: 72,
        fontWeight: 'bold',
        color: '#2d6a4f'
    },
    headerSection: {
        marginBottom: 16,
        borderBottomWidth: 2,
        borderBottomColor: '#2d6a4f',
        paddingBottom: 8
    },
    mainTitle: {
        fontSize: 22,
        fontWeight: 'bold',
        color: '#1b4332',
        marginBottom: 4
    },
    brandSub: {
        fontSize: 9,
        color: '#6b7280',
        marginBottom: 8
    },
    metaBox: {
        backgroundColor: '#f8fafc',
        borderLeftWidth: 4,
        borderLeftColor: '#2d6a4f',
        padding: 8,
        borderRadius: 4,
        marginBottom: 12
    },
    plantMeta: {
        fontSize: 12,
        fontWeight: 'bold',
        color: '#047857',
        marginBottom: 2
    },
    diseaseMeta: {
        fontSize: 12,
        fontWeight: 'bold',
        color: '#991b1b',
        marginBottom: 2
    },
